#!/usr/bin/env bash

set -Eeuo pipefail

# Turns a small Debian/Armbian board (Orange Pi Zero 3, Raspberry Pi, ...) into an always-on proxy
# source for lap-vision-f1 - the unattended equivalent of `make tunnel` / the phone's SSH client:
#   f1-socks.service           microsocks on 127.0.0.1:SOCKS_PORT (home connection's IP)
#   f1-tunnel.service          ssh -R 127.0.0.1:SOCKS_PORT on the VPS -> that microsocks,
#                              restarted by systemd whenever ssh exits (keepalive timeout, Wi-Fi drop)
#   f1-tunnel-watchdog.timer   every 2 min: Wi-Fi/gateway, local SOCKS and an end-to-end check
#                              through the VPS; restarts whatever is broken, reboots as a last resort
# On the VPS, f1-proxy-relay.sh picks the port up once it is listed in PROXY_TUNNEL_PORTS
# (GitHub variable F1_PROXY_TUNNEL_PORTS). See README.md in this directory.
#
# Idempotent - re-run after changing settings or adding a Wi-Fi network.
# Usage (on the board, as root - run it there, not via `ssh host '...'`, so the Wi-Fi password
# stays out of the laptop's shell history):
#   SOCKS_PORT=1082 bash install.sh
#   WIFI_SSID='Home' WIFI_PASSWORD='...' SOCKS_PORT=1082 bash install.sh   # also joins Wi-Fi

TUNNEL_USER="${TUNNEL_USER:-ubuntu}"
TUNNEL_HOST="${TUNNEL_HOST:-95.179.154.60}"
TUNNEL_PORT="${TUNNEL_PORT:-22}"
SOCKS_PORT="${SOCKS_PORT:-1082}"
# Second reverse forward to this board's sshd, for admin access through the VPS; empty disables it.
ADMIN_PORT="${ADMIN_PORT-2222}"
WIFI_IFACE="${WIFI_IFACE:-wlan0}"
WIFI_SSID="${WIFI_SSID:-}"
WIFI_PASSWORD="${WIFI_PASSWORD:-}"

SERVICE_USER="f1tunnel"
STATE_DIR="/var/lib/f1-tunnel"
CONF_DIR="/etc/f1-tunnel"
LIB_DIR="/usr/local/lib/f1-tunnel"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

log() {
  printf '[f1-pi] %s\n' "$*"
}

[[ ${EUID} -eq 0 ]] || { echo "run as root: sudo bash $0" >&2; exit 1; }

log "installing packages"
apt-get update -qq
# avahi-daemon makes the board reachable as <hostname>.local from the laptop.
DEBIAN_FRONTEND=noninteractive apt-get install -y -qq openssh-client openssh-server curl iputils-ping iw avahi-daemon >/dev/null
if ! DEBIAN_FRONTEND=noninteractive apt-get install -y -qq microsocks >/dev/null 2>&1; then
  log "microsocks not packaged here, building it from source"
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq build-essential git >/dev/null
  build_dir="$(mktemp -d)"
  git clone -q --depth 1 https://github.com/rofl0r/microsocks "${build_dir}"
  make -s -C "${build_dir}"
  install -m 755 "${build_dir}/microsocks" /usr/local/bin/microsocks
  rm -rf "${build_dir}"
fi
# The unit always points at /usr/local/bin, whichever way microsocks was installed.
if [[ ! -x /usr/local/bin/microsocks ]]; then
  ln -sf "$(command -v microsocks)" /usr/local/bin/microsocks
fi

if ! id -u "${SERVICE_USER}" >/dev/null 2>&1; then
  log "creating system user ${SERVICE_USER}"
  useradd --system --home-dir "${STATE_DIR}" --shell /usr/sbin/nologin "${SERVICE_USER}"
fi
install -d -m 700 -o "${SERVICE_USER}" -g "${SERVICE_USER}" "${STATE_DIR}"
install -d -m 755 "${CONF_DIR}" "${LIB_DIR}"

if [[ ! -f "${STATE_DIR}/id_ed25519" ]]; then
  log "generating SSH key for the tunnel"
  runuser -u "${SERVICE_USER}" -- ssh-keygen -q -t ed25519 -N '' -C "f1-tunnel@$(hostname)" -f "${STATE_DIR}/id_ed25519"
fi

cat > "${CONF_DIR}/ssh_config" <<EOF
# Generated by deploy/pi/install.sh - re-run it to change. Shared by f1-tunnel and the watchdog.
Host vps
  HostName ${TUNNEL_HOST}
  User ${TUNNEL_USER}
  Port ${TUNNEL_PORT}
  IdentityFile ${STATE_DIR}/id_ed25519
  IdentitiesOnly yes
  BatchMode yes
  UserKnownHostsFile ${STATE_DIR}/known_hosts
  StrictHostKeyChecking accept-new
  ConnectTimeout 15
  ServerAliveInterval 15
  ServerAliveCountMax 3
  ExitOnForwardFailure yes
EOF
chmod 644 "${CONF_DIR}/ssh_config"

cat > "${CONF_DIR}/tunnel.env" <<EOF
# Generated by deploy/pi/install.sh - re-run it to change.
SOCKS_PORT=${SOCKS_PORT}
ADMIN_PORT=${ADMIN_PORT}
WIFI_IFACE=${WIFI_IFACE}
EOF

install -m 755 "${here}/f1-tunnel.sh" "${LIB_DIR}/f1-tunnel.sh"
install -m 755 "${here}/f1-tunnel-watchdog.sh" "${LIB_DIR}/f1-tunnel-watchdog.sh"
for unit in f1-socks.service f1-tunnel.service f1-tunnel-watchdog.service f1-tunnel-watchdog.timer; do
  install -m 644 "${here}/${unit}" "/etc/systemd/system/${unit}"
done

if command -v nmcli >/dev/null 2>&1; then
  log "NetworkManager: Wi-Fi power saving off, Wi-Fi connections retry forever"
  install -d -m 755 /etc/NetworkManager/conf.d
  printf '[connection]\nwifi.powersave = 2\n' > /etc/NetworkManager/conf.d/f1-wifi-powersave-off.conf
  # By default NM gives up on a connection after 4 failed attempts until reboot.
  while IFS=: read -r name type; do
    [[ "${type}" == "802-11-wireless" ]] || continue
    nmcli connection modify "${name}" connection.autoconnect yes connection.autoconnect-retries 0
  done < <(nmcli -t -f NAME,TYPE connection show)
  systemctl reload NetworkManager || true
else
  # Armbian minimal: netplan + systemd-networkd, wpa_supplicant reconnects on its own forever.
  if [[ -n "${WIFI_SSID}" ]]; then
    log "netplan: joining Wi-Fi ${WIFI_SSID} on ${WIFI_IFACE}"
    # Same file Armbian's first-run Wi-Fi preset writes, so a re-run replaces it instead of adding one.
    wifi_netplan="/etc/netplan/30-wifis-dhcp.yaml"
    cat > "${wifi_netplan}" <<EOF
network:
  version: 2
  renderer: networkd
  wifis:
    ${WIFI_IFACE}:
      dhcp4: yes
      dhcp6: yes
      access-points:
        "${WIFI_SSID}":
          password: "${WIFI_PASSWORD}"
EOF
    chmod 600 "${wifi_netplan}"
    netplan apply
  fi
  log "Wi-Fi power saving off (udev rule)"
  printf 'ACTION=="add", SUBSYSTEM=="net", KERNEL=="wlan*", RUN+="/usr/sbin/iw dev %%k set power_save off"\n' \
    > /etc/udev/rules.d/70-f1-wifi-powersave-off.rules
  iw dev "${WIFI_IFACE}" set power_save off 2>/dev/null || true
fi

log "capping the systemd journal at 20M"
install -d -m 755 /etc/systemd/journald.conf.d
printf '[Journal]\nSystemMaxUse=20M\nRuntimeMaxUse=20M\nMaxRetentionSec=2week\n' > /etc/systemd/journald.conf.d/f1-size.conf
systemctl restart systemd-journald

if [[ -e /dev/watchdog ]]; then
  log "enabling the hardware watchdog (reboots the board if the kernel/systemd hangs)"
  install -d -m 755 /etc/systemd/system.conf.d
  printf '[Manager]\nRuntimeWatchdogSec=15s\nRebootWatchdogSec=2min\n' > /etc/systemd/system.conf.d/f1-watchdog.conf
  systemctl daemon-reexec
fi

systemctl daemon-reload
systemctl enable --now ssh >/dev/null 2>&1 || true
systemctl enable f1-socks.service f1-tunnel.service f1-tunnel-watchdog.timer >/dev/null
systemctl restart f1-socks.service f1-tunnel.service f1-tunnel-watchdog.timer

permitlisten="permitlisten=\"127.0.0.1:${SOCKS_PORT}\""
[[ -z "${ADMIN_PORT}" ]] || permitlisten+=",permitlisten=\"127.0.0.1:${ADMIN_PORT}\""
cat <<EOF

[f1-pi] Installed. Remaining steps on the VPS (${TUNNEL_USER}@${TUNNEL_HOST}), see README.md:

1. Append this line to ~${TUNNEL_USER}/.ssh/authorized_keys - the key can only open the forwards
   below and run the health check, nothing else:

restrict,port-forwarding,${permitlisten},command="curl -sS --max-time 15 --socks5-hostname 127.0.0.1:${SOCKS_PORT} https://api.ipify.org" $(cat "${STATE_DIR}/id_ed25519.pub")

2. Add ${SOCKS_PORT} to the GitHub variable F1_PROXY_TUNNEL_PORTS and redeploy.

The tunnel retries every 10s on its own; watch it with: journalctl -fu f1-tunnel -u f1-tunnel-watchdog
EOF
